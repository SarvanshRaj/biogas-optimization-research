"""Five-seed evaluation of the simulated study - SIMULATED data only.

Everything here describes a *simulator*. A model trained on these tables learns the
assumptions written in `src/config.py`; the scores below are not evidence about real food
waste or real digesters, and every artefact this module writes carries the SIMULATED marker.

The frozen protocol this implements is `docs/model_specification.md` §9:

* scenario-grouped 70/15/15 split, replicates staying with their scenario;
* preprocessing fit on the training split only (done in `src/train_models.py`);
* the test split is opened once, at the end, for every seed;
* metrics reported as **mean plus spread over the seeds** - descriptive, never inferential;
* the held-out family of §8 reported separately and never used for fitting;
* feature importance labelled "what the model used", never "what drives the biology";
* the pre-declared decision rules of §9.1 evaluated from the collected numbers.

Plotting uses the Agg backend so the module runs headless in CI and in the sandbox.
"""

from __future__ import annotations

import argparse
import json
